// 口语区间档位的**唯一来源**。
//
// 为什么单独抽一个文件：
//   定稿时踩过一个真实的坑——同一个词「六成半」，在 sync-card-numbers.mjs 的
//   spoken() 里定义为 66%~72%，在 verify-numbers.mjs 的断言里却写成 60%~70%。
//   两套边界各自看着都合理，但从没被放在一起对过。
//   实测弹幕 ≤10 字 = 71.3% 时，sync 判「落在六成半档」于是把卡片写成「六成半」，
//   verify 判「71.3 >= 70 超出六成半」于是判红。定稿当天直接失败一项。
//
//   根因不是哪个数字写错，而是**同一个概念有两份定义**。
//   所以这里只定义一次，两个脚本都从这里 import，边界再也不会各走各的。
//
// 档位的语义（关键：每个档位的**实际覆盖范围**必须配得上它的字面含义）：
//   「六成半」字面就是 65%，所以它只该覆盖离 65 很近的一小段，
//   绝不能宽容到 71%——那已经是「七成多」了，读的人会觉得被误导。
//   宁可让档位窄一点、落到兜底的「约 N%」，也不要让措辞系统性偏大。

// [下界, 上界, 说法]，按上界升序排列，相邻档位首尾相接不留缝。
// 判档规则：pct >= lo && pct < hi
export const BANDS = [
  [30, 36, '三成多'],   // 30~35：三成多
  [36, 42, '四成'],     // 36~41：四成（36 起算，容得下 39.1 这种）
  [42, 48, '四成多'],
  [48, 55, '近五成'],
  [55, 60, '接近六成'],
  [60, 64, '六成'],     // 60~63：就是「六成」本身
  [64, 67, '六成半'],   // 64~66：紧贴 65，最窄的一档
  [67, 74, '七成'],     // 67~73：说「七成」，容得下 71.3
  [74, 80, '七成多'],
  [80, 90, '八成以上'],
  [90, Infinity, '九成'],
];

// 把百分比换算成最贴切的口语说法；落不进任何档位时退回「约 N%」。
export function spoken(pct) {
  for (const [lo, hi, word] of BANDS) {
    if (pct >= lo && pct < hi) return word;
  }
  return `约${Math.round(pct)}%`;
}

// 反过来：给定说法，返回它承诺的百分比区间 [lo, hi)；不认识的词返回 null。
// verify 用这个把「卡片写的什么」翻译成区间，再和实测比——
// 这样两边的口径天然一致，不可能再出现 66~72 对 60~70 那种错位。
export function bandOf(word) {
  const hit = BANDS.find(([, , w]) => w === word);
  return hit ? [hit[0], hit[1]] : null;
}

// 正则用的一串候选（长词在前，避免 alternation 先吃掉短词）。
// 放在这里而不是各脚本手写：sync 和 verify 必须认**同一批**说法，
// 否则加了一档却忘了同步正则，就会出现「卡片写得对、校验判红」。
export const SPOKEN_PATTERN = '(?:三成多|四成多?|近五成|接近六成|六成半|六成|七成多|七成|八成以上|九成|约\\d+(?:\\.\\d+)?%)';
