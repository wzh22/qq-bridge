/**
 * 内部独白检测（narration guard）。
 *
 * ── 要解决的问题 ──────────────────────────────────────────────────────────
 *
 * reserved2 模式下有个「兜底转发」：本轮开始时还有对方的消息没被回应，
 * 而 AI 只输出了正文、没调用任何发送工具 —— 这时把正文直接发给对方，
 * 否则用户会觉得消息发不出去。
 *
 * 但这个兜底有个盲区：AI 有时输出的**不是要发给对方的话**，而是它自己
 * 对刚才这轮的复盘叙述。实测被误发出去的两条：
 *
 *   「他应了句"好啊"，早点睡这事就算说定了。我没再多说，观察满五分钟就收尾了。」
 *   「他说"你发一个语音"，我就录了一句发过去，说的是"早点躺吧，别又熬到十二点了"。
 *     他没再接话，观察满五分钟就收尾了。」
 *
 * 这两句都是对的描述，但它们是**说给自己听**的。发出去后对方看到的是
 * "bot 在跟谁汇报"，非常出戏。
 *
 * ── 为什么用规则而不是让模型判断 ──────────────────────────────────────────
 *
 * 这个检查在发送路径上，每条消息都要过。加一次模型调用意味着：
 * 多一次推理成本、多几十毫秒延迟、以及一个会失败的依赖点。
 * 而这类文本的特征相当稳定（第一人称叙述 + 元动作 + 引用原话），
 * 用规则可以做到零成本、零延迟、可单测。
 *
 * ── 判定策略 ──────────────────────────────────────────────────────────────
 *
 * 不追求「命中任一特征就拦」—— 那样会误杀大量正常回复
 * （「他说他要考联考」这种第一人称对话本身完全正常）。
 * 采用**计分 + 阈值**：命中 ≥ MIN_HITS 项才判为独白。
 *
 * 阈值 2 是实测出来的：真实泄露文本命中 4~6 项，
 * 正常回复最多 1 项（带个「他说」而已）。
 */

/** 判定为独白所需的最少命中项数。调低会误杀，调高会漏放。 */
export const MIN_HITS = 2;

/**
 * 特征表。每条都对应「AI 在描述自己刚才做了什么」的典型句式。
 *
 * 注意每条都刻意写得**窄**：宁可在这一层漏一些，也不要在发送路径上误杀。
 * 漏掉的还有第二层兜底（见 bridge 里的日志与活动记录）。
 */
const FEATURES = [
  // 「观察满五分钟」「过了两小时」—— 复盘里才会出现的时间度量。
  // 中文数字也必须覆盖：「过了两小时」用 \d+ 匹配不到（实测漏判过一条）。
  {
    id: 'metaTime',
    re: /(满|过了|等了|隔了)\s*(五分钟|十分钟|半小时|[一二三四五六七八九十百\d]+\s*(分钟|小时|天))/
  },

  // 「观察/收尾/继续等/潜水」—— 描述自己的处理动作，不是在跟人说话
  { id: 'metaAction', re: /(观察|收尾|继续等|继续待|待着|潜水|不硬找|先收在|记一笔|把话收)/ },

  // 「我就录了一句发过去」「我再问了一句」—— 叙述已完成动作
  { id: 'narrateSelf', re: /我(就|又|也|先|再|才)(录|发|说|问|应|回|看|等|待|收)了?/ },

  // 引用别人的原话，且整句在转述（配合其他特征用）
  { id: 'quoted', re: /[“"「][^”"」]{2,}[”"」]/ },

  // 第三人称叙述对方：「他应了句」「她没再说话」
  { id: 'thirdPerson', re: /(^|[，。！？\s])(他|她)(应|说|问|没再|又|回|答|发)/ },

  // 解释因果/自己这一侧：「所以我就」「这边也」
  { id: 'explain', re: /(所以|于是|因此|这边也|本轮|这次我)/ },

  // 「（不）再多说」「就到这」这类收束语
  { id: 'wrapUp', re: /(没再多说|就到这|先这样|算了不说|不再多说)/ },

  // 「没人说话 / 没人应 / 没出现」—— 描述对方的沉默状态，是复盘而非对话
  {
    id: 'silence',
    re: /(没人(说话|回|应|出声|出现)|一直没(出声|出现|回)|没再接话|没再回)/
  },

  // ── 第二组：纯叙述体的复盘（2026-11-03 补）──────────────────────────
  //
  // 第一组特征偏向「观察/收尾/潜水」这类显式元动作，但实测有一种纯叙述体
  // 完全逃过了检测：
  //   「他这么早又让我发语音，我再发了一条，刚醒，声音还有点发懵。
  //     他没回，估计听了就去忙。不知道这次声音他听着怎么样。」
  // 它没有一个元动作词，但通篇在用「他」指代对话对象——这是第三人称叙述，
  // 不是对「你」说话。正常回复里指代对方一律用「你」，用「他」就是在转述。

  // 「他也还没动静」「他没回」「他这么早又」—— 用第三人称描述当前对话对象。
  //
  // 注意这里**不包含**「估计/应该」这类推测词：它们属于下面的 speculate。
  // 第一版把「估计」也写进来，导致「他估计在忙吧」被 two 个特征同时命中、
  // 凑够 2 分误杀了一句正常回复（测试抓到的）。同一句话不该被重复计分。
  {
    id: 'thirdAction',
    re: /(^|[，。！？\s])(他|她)(这么|那么|又|还|也|没|就|才|一直|这两天|今天)/
  },

  // 「我再发了一条」「我又问了一句」—— 叙述自己刚完成的动作
  { id: 'selfNarrate', re: /我(又|再|就|才|也|先)(发|录|说|问|应|回|看|等|待|收)了/ },

  // 「估计听了就去忙」「不知道这次…怎么样」—— 揣测对方反应/自我评估
  { id: 'speculate', re: /(估计|大概|有可能|不知道这次|应该会|想必)/ },
  { id: 'selfEval', re: /(声音|语气|表现|回复).{0,6}(怎么样|如何|还行|好不好)/ }
];

/** 单个特征的命中详情，便于日志解释「为什么判成独白」。 */
export function detectNarrationFeatures(text) {
  const s = String(text ?? '');
  if (!s.trim()) return [];
  return FEATURES.filter((f) => f.re.test(s)).map((f) => f.id);
}

/**
 * 判断一段正文是否是「内部独白」。
 *
 * @param {string} text
 * @param {object} opts
 * @param {number} opts.minHits 覆盖默认阈值（测试与灰度调节用）
 * @returns {{isNarration: boolean, hits: string[], score: number}}
 */
export function detectNarration(text, { minHits = MIN_HITS } = {}) {
  const hits = detectNarrationFeatures(text);
  return {
    isNarration: hits.length >= minHits,
    hits,
    score: hits.length
  };
}

/**
 * 给模型看的提醒语。
 *
 * 为什么还要提醒而不是只靠拦截：拦下来消息就丢了，对方什么都收不到，
 * 体验更差。所以拦下的同时**回灌一条提示**，让它下一轮正常说话。
 */
export const NARRATION_NUDGE =
  '【提醒】你刚才那段输出是写给自己的复盘，不是要发给对方的话，已经拦下没有发送。' +
  '如果还有话要对他说，直接用 qq_send_message 发出去；没有话就不必补。';
