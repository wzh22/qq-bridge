// 语气锚点（tone anchor）：一小段「示范对话」，用来把被稀释的语气拉回来。
//
// ── 为什么需要它 ────────────────────────────────────────────────────────
//
// 长会话里，人格卡只在 bootstrap 注入一次（22KB），之后上下文压缩会把它截到
// 5KB 左右，此后每轮只剩一行「【当前角色】xxx」。语气就靠那点残余撑着，
// 越聊越稀释——表现出来就是「上下文压缩后像换了个人」。
//
// 依据：Accenture 的 ContextEcho（arXiv 2605.24279，实测 23 个前沿模型）三条结论
//   1. 人格漂移是通用现象，不是某一家模型的问题；
//   2. 会话内压缩**不能**可靠地重置它（compaction does not reliably reset it）；
//   3. **一个约 110 token 的锚点回合就能恢复**，且效果维持 20+ 轮。
//
// 第 3 条是关键：修语气不需要重发整张人格卡，一小段示范就够。而且锚点是
// **对话样例**（user 问 → assistant 答），不是规则描述——对模型来说，
// 「这样回」的示范比「你要这样回」的说明有效得多。
//
// ── 为什么选这几句 ──────────────────────────────────────────────────────
//
// 示范要同时立住这个人格最难自动学到的几件事：
//   · 短、空格分句（人格卡里的分条规则）
//   · 不客套、不复述对方（禁用词表要防的 AI 腔）
//   · 有判断、不只是附和（「不做应声虫」）
//   · 关心但不腻（女生口吻，不是撒娇）
//
// 内容是**虚构的日常对话**，故意挑最普通的话题（跑步、随便聊），
// 免得模型把示范里的具体事（膝盖、一千米）当成真实记忆去接话。
// 所以下文明确写了「不是照抄内容」。

export const TONE_ANCHOR = [
  '【语气示范】',
  '下面是给你看的**语气样例**，不是要发出去的内容，也不是真实发生过的事。照这个说话方式，别照抄句子、别接示范里的话题。',
  '',
  '对方：今天跑完一千米腿有点抖',
  '你：刚开始都这样 歇会儿 明天估计更酸',
  '对方：哈哈那我明天不跑了',
  '你：也行 别硬撑 疼了跟我说',
  '',
  '（看点：短句、空格断开、不客套、不复述对方的话、有自己的判断。）'
].join('\n');

/** 锚点大致占多少字符，供控制台/测试核对成本。 */
export const TONE_ANCHOR_CHARS = TONE_ANCHOR.length;